test_that("the toy data load with the documented columns", {
  skip_if_no_toy_data()
  toy <- denmark_toy_data()
  expect_s3_class(toy, "data.frame")
  expect_named(toy, c("x", "y", "celltype", "geneA", "geneB", "geneC"))
  expect_equal(nrow(toy), 7449)
  expect_equal(c(table(toy$celltype)), c(Other = 4000L, Tumor = 3449L))
  expect_true(all(toy$x >= 0 & toy$x <= 6 & toy$y >= 0 & toy$y <= 4))
  counts <- unlist(toy[c("geneA", "geneB", "geneC")])
  expect_true(all(counts >= 0 & counts == round(counts)))
  expect_true(all(stats::complete.cases(toy)))
})

test_that("the toy tissue boundary and grid match the parity fixture", {
  skip_if_no_toy_data()
  skip_if_not_installed("sf")
  skip_if_not_installed("jsonlite")
  fixture <- test_path("..", "..", "python", "tests", "data", "toy_stan_data_boundary.json")
  skip_if_not(file.exists(fixture), "parity fixture not found (source checkout only)")
  ref <- jsonlite::read_json(fixture, simplifyVector = TRUE)
  toy <- denmark_toy_data()
  tissue <- denmark_alpha_shape(toy$x, toy$y)
  tumor <- subset(toy, celltype == "Tumor", select = -celltype)
  prep <- denmark_prepare(tumor, gene = "geneA", grid_size = 10, basis = 10,
                          boundary = tissue)
  expect_equal(attr(tissue, "alpha"), ref$alpha, tolerance = 1e-12)
  expect_equal(as.numeric(sf::st_area(tissue)), ref$tissue_area, tolerance = 1e-12)
  expect_equal(prep$grid$type, ref$grid_type)
  expect_equal(prep$grid$area, ref$grid_area, tolerance = 1e-12)
  expect_equal(prep$stan_data$y1, ref$stan_data$y1)
  expect_equal(prep$stan_data$log_grid_area, ref$stan_data$log_grid_area, tolerance = 1e-12)
})
